#!/usr/bin/env python3
"""
report.py — render a merged benchmark table as Markdown.

Reads merge.py output and emits the side-by-side table. Replaces the five ad-hoc
scripts in EventProp.Python.Benchmarks/ (generate_report.py, parse_benchmarks.py,
print_full_matrix.py, print_native_comparison.py, print_poisson_comparison.py).

Usage:
    report.py merged.json --out report.md

Design rules, all traceable to BENCHMARK_SCHEMA.md:

  * Ratios are computed here, from stored mean_ns per impl. The record format stores
    no ratio, so adding a pair (e.g. Managed/Eigen) needs no re-run.
  * Every ratio names both implementations in words. The three suites currently use
    three opposite sign conventions (Eigen/C >1 wins, Native/Managed <1 wins,
    Cython/pybind11 >1 slower); a reader must not have to remember them.
  * Geomeans use valid cells ONLY, and state how many cells they used.
  * Excluded rows are listed with their computed reasons. No "*" footnotes.
  * Provenance is printed per suite, including tool_version — a BenchmarkDotNet
    version change moves the .NET headline Ratio 8-12%, so a version change must be
    visible as a discontinuity, not a silent shift.
"""

import argparse
import json
import math
import sys

SCHEMA_VERSION = 1

# Declared comparison pairs. One entry per pair — the report prints the winner in
# words ("C is 1.19x faster than Eigen"), so direction never depends on a sign
# convention and a reversed duplicate would be pure noise. The three suites
# historically used three opposite conventions (Eigen/C >1 wins, Native/Managed <1
# wins, Cython/pybind11 >1 slower); this table replaces all three.
# Order is (reference, comparison): the ratio column is time(comparison)/time(reference).
PAIRS = [
    ("C", "Eigen"),
    ("C", "Managed"),
    ("PInvoke", "Managed"),
    ("Cython", "pybind11"),
]

SIZE_ORDER = ["Tiny", "Small", "Medium", "Large", "XL"]
PATTERN_ORDER = ["uniform", "poisson", "burst"]


def fmt_us(ns):
    """Human time. ns -> us keeps the table readable at benchmark scale."""
    return f"{ns / 1000.0:,.2f}"


def geomean(values):
    if not values:
        return None
    return math.exp(sum(math.log(v) for v in values) / len(values))


def ratio(cell, a, b):
    """time(b) / time(a). >1 means a took less time, i.e. a is FASTER."""
    ia, ib = cell["impls"].get(a), cell["impls"].get(b)
    if not ia or not ib:
        return None
    if not ia["mean_ns"] or not ib["mean_ns"]:
        return None
    return ib["mean_ns"] / ia["mean_ns"]


def winner_phrase(a, b, r):
    if r is None:
        return None
    if abs(r - 1.0) < 0.02:
        return f"{a} / {b} parity ({r:.2f}x)"
    if r > 1:
        return f"{a} is {r:.2f}x faster than {b}"
    inv = 1.0 / r
    return f"{b} is {inv:.2f}x faster than {a}"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("merged_json")
    ap.add_argument("--out", required=True)
    ap.add_argument("--title", default="Benchmark comparison",
                    help="H1 heading; pass 'Library Benchmark Comparison' to "
                         "generate BENCHMARKS.md")
    ap.add_argument("--source", default=None,
                    help="How the input was produced, e.g. the run_all.py command")
    args = ap.parse_args()

    with open(args.merged_json) as f:
        doc = json.load(f)
    if doc.get("schema_version") != SCHEMA_VERSION:
        print(f"schema_version {doc.get('schema_version')!r}, expected {SCHEMA_VERSION}",
              file=sys.stderr)
        return 2

    cells = doc["cells"]
    size_cells = [c for c in cells if c["axis"] is None]
    sweeps = [c for c in cells if c["axis"] is not None]

    L = []
    L.append(f"# {args.title}")
    L.append("")
    L.append("Generated by `scripts/bench/report.py` from `merge.py` output. "
             "Do not hand-edit.")
    if args.source:
        L.append("")
        L.append(f"Input: `{args.source}`")
    L.append("")

    # ── Provenance ───────────────────────────────────────────────────
    L.append("## Provenance")
    L.append("")
    prov = doc.get("provenance", {})
    L.append(f"- hosts: {', '.join(prov.get('hosts', []))}")
    for suite, tools in sorted((prov.get("tools") or {}).items()):
        L.append(f"- suite `{suite}`: {'; '.join(tools)}")
    L.append(f"- sources: {', '.join(prov.get('sources', []))}")
    L.append("")
    L.append("> A BenchmarkDotNet version change invalidates historical .NET "
             "comparisons (AGENTS.md: 8-12% on the headline Ratio, 0.6% noise "
             "floor). Check `tool_version` before comparing two runs.")
    L.append("")

    # ── Per-pair tables ──────────────────────────────────────────────
    for a, b in PAIRS:
        pair_cells = [c for c in size_cells if a in c["impls"] and b in c["impls"]]
        if not pair_cells:
            continue
        # A pair whose impls are the same underlying implementation aliased two ways
        # (C and PInvoke are both the C library) is not a comparison — skip it.
        if {a, b} == {"C", "PInvoke"}:
            continue
        L.append(f"## {a} vs {b}")
        L.append("")
        L.append(f"Ratio column: time({b}) / time({a}). "
                 f">1 means **{a} is faster**, <1 means **{b} is faster**.")
        L.append("")
        L.append("| benchmark | size | pattern | " + a + " (us) | " + b + " (us) | ratio | valid |")
        L.append("|---|---|---|---:|---:|---:|:--|")

        def sort_key(c):
            return (c["benchmark"],
                    SIZE_ORDER.index(c["size"]) if c["size"] in SIZE_ORDER else 99,
                    PATTERN_ORDER.index(c["pattern"]) if c["pattern"] in PATTERN_ORDER else 99)

        ratios_valid = []
        for c in sorted(pair_cells, key=sort_key):
            r = ratio(c, a, b)
            ta = fmt_us(c["impls"][a]["mean_ns"])
            tb = fmt_us(c["impls"][b]["mean_ns"])
            flag = "yes" if c["valid"] else "—"
            rs = f"{r:.2f}x" if r else ""
            L.append(f"| {c['benchmark']} | {c['size']} | {c['pattern']} | {ta} | {tb} | {rs} | {flag} |")
            if c["valid"] and r:
                ratios_valid.append(r)

        g = geomean(ratios_valid)
        L.append("")
        if g:
            L.append(f"**Geomean over {len(ratios_valid)} valid cells: "
                     f"{winner_phrase(a, b, g)}**")
        else:
            L.append("**Geomean: no valid cells for this pair**")
        L.append("")

    # ── Excluded rows ────────────────────────────────────────────────
    excluded = [c for c in size_cells if not c["valid"]]
    if excluded:
        L.append("## Excluded from geomeans")
        L.append("")
        L.append("Validity is computed by `merge.py` from `output_spikes`, "
                 "`error_code`, iteration count, and the declared exclusion policy. "
                 "It is not hand-authored.")
        L.append("")
        L.append("| benchmark | size | pattern | reason |")
        L.append("|---|---|---|---|")
        for c in sorted(excluded, key=lambda c: (c["benchmark"], str(c["size"]))):
            L.append(f"| {c['benchmark']} | {c['size']} | {c['pattern']} | "
                     f"{', '.join(c['invalid_reasons'])} |")
        L.append("")

    # ── Sweeps ───────────────────────────────────────────────────────
    if sweeps:
        L.append("## Parameter sweeps")
        L.append("")
        L.append("Kept out of the size table; these vary a parameter, not a size cell.")
        L.append("")
        L.append("| benchmark | axis | impl | time (us) |")
        L.append("|---|---|---|---:|")
        for c in sorted(sweeps, key=lambda c: (c["benchmark"], str(c["axis"]))):
            for impl, row in sorted(c["impls"].items()):
                L.append(f"| {c['benchmark']} | {json.dumps(c['axis'])} | {impl} | "
                         f"{fmt_us(row['mean_ns'])} |")
        L.append("")

    with open(args.out, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"{args.out}: {len(size_cells)} size cells, "
          f"{len(excluded)} excluded, {len(sweeps)} sweep cells")
    return 0


if __name__ == "__main__":
    sys.exit(main())
