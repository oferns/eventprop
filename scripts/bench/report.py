#!/usr/bin/env python3
"""
report.py — render a merged benchmark table as Markdown.

Reads merge.py output and emits the side-by-side table. Replaces the five ad-hoc
scripts in EventProp.Python.Benchmarks/ (generate_report.py, parse_benchmarks.py,
print_full_matrix.py, print_native_comparison.py, print_poisson_comparison.py).

Usage:
    report.py merged.json --out report.md

Design rules, all traceable to BENCHMARK_SCHEMA.md:

  * Ratios are computed here, from stored mean_ns per impl. The record format stores
    no ratio, so adding a pair (e.g. Managed/Eigen) needs no re-run.
  * Every ratio names both implementations in words. The three suites currently use
    three opposite sign conventions (Eigen/C >1 wins, Native/Managed <1 wins,
    Cython/pybind11 >1 slower); a reader must not have to remember them.
  * Geomeans use valid cells ONLY, and state how many cells they used.
  * Excluded rows are listed with their computed reasons. No "*" footnotes.
  * Provenance is printed per suite, including tool_version — a BenchmarkDotNet
    version change moves the .NET headline Ratio 8-12%, so a version change must be
    visible as a discontinuity, not a silent shift.
"""

import argparse
import json
import math
import sys

SCHEMA_VERSION = 1

# Declared comparison pairs. One entry per pair — the report prints the winner in
# words ("C is 1.19x faster than Eigen"), so direction never depends on a sign
# convention and a reversed duplicate would be pure noise. The three suites
# historically used three opposite conventions (Eigen/C >1 wins, Native/Managed <1
# wins, Cython/pybind11 >1 slower); this table replaces all three.
# Order is (reference, comparison): the ratio column is time(comparison)/time(reference).
# Labels are explicit about measurement CONTEXT, because "C" alone is ambiguous: the
# native suite measures the C library directly, while the .NET suite reaches the same
# library through P/Invoke. Those are different measurements (marshalling cost is on the
# C side of the .NET ratio), so they are separate impls and separate pairs. The chain
# closes as Eigen <-> C <-> PInvoke <-> Managed, each adjacent pair measured.
PAIRS = [
    ("C", "Eigen"),
    ("C", "PInvoke"),
    ("PInvoke", "Managed"),
    ("Cython", "pybind11"),
]

# Human-readable section titles; the impl names stay terse for the table columns.
PAIR_TITLES = {
    ("C", "Eigen"): "C (native) vs Eigen (native)",
    ("C", "PInvoke"): "C (native) vs C via P/Invoke (.NET)",
    ("PInvoke", "Managed"): "C via P/Invoke (.NET) vs Managed (.NET)",
    ("Cython", "pybind11"): "Cython vs pybind11",
}

SIZE_ORDER = ["Tiny", "Small", "Medium", "Large", "XL"]
PATTERN_ORDER = ["uniform", "poisson", "burst"]


def fmt_us(ns):
    """Human time. ns -> us keeps the table readable at benchmark scale."""
    return f"{ns / 1000.0:,.2f}"


def geomean(values):
    if not values:
        return None
    return math.exp(sum(math.log(v) for v in values) / len(values))


def ratio(cell, a, b):
    """time(b) / time(a). >1 means a took less time, i.e. a is FASTER."""
    ia, ib = cell["impls"].get(a), cell["impls"].get(b)
    if not ia or not ib:
        return None
    if not ia["mean_ns"] or not ib["mean_ns"]:
        return None
    return ib["mean_ns"] / ia["mean_ns"]


def winner_phrase(a, b, r):
    if r is None:
        return None
    if abs(r - 1.0) < 0.02:
        return f"{a} / {b} parity ({r:.2f}x)"
    if r > 1:
        return f"{a} is {r:.2f}x faster than {b}"
    inv = 1.0 / r
    return f"{b} is {inv:.2f}x faster than {a}"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[1])
    ap.add_argument("merged_json")
    ap.add_argument("--out", required=True)
    ap.add_argument("--title", default="Benchmark comparison",
                    help="H1 heading; pass 'Library Benchmark Comparison' to "
                         "generate BENCHMARKS.md")
    ap.add_argument("--source", default=None,
                    help="How the input was produced, e.g. the run_all.py command")
    args = ap.parse_args()

    with open(args.merged_json) as f:
        doc = json.load(f)
    if doc.get("schema_version") != SCHEMA_VERSION:
        print(f"schema_version {doc.get('schema_version')!r}, expected {SCHEMA_VERSION}",
              file=sys.stderr)
        return 2

    cells = doc["cells"]
    size_cells = [c for c in cells if c["axis"] is None]
    sweeps = [c for c in cells if c["axis"] is not None]

    L = []
    L.append(f"# {args.title}")
    L.append("")
    L.append("Generated by `scripts/bench/report.py` from `merge.py` output. "
             "Do not hand-edit.")
    if args.source:
        L.append("")
        L.append(f"Input: `{args.source}`")
    L.append("")

    # ── Provenance ───────────────────────────────────────────────────
    L.append("## Provenance")
    L.append("")
    prov = doc.get("provenance", {})
    L.append(f"- hosts: {', '.join(prov.get('hosts', []))}")
    # Commit + date + dirty flag. A committed report is a durable artifact that
    # outlives the code it describes; without these, a reader cannot tell whether
    # it predates a change they care about, and stale numbers read like fresh ones.
    revs = prov.get("vcs_rev") or []
    if revs:
        L.append(f"- vcs_rev: {', '.join(revs)}"
                 + ("  _(records span multiple commits)_" if len(revs) > 1 else ""))
    dirty = prov.get("vcs_dirty")
    if dirty is not None:
        L.append(f"- vcs_dirty: {dirty}")
    dates = prov.get("date") or []
    if dates:
        L.append(f"- date: {', '.join(dates)}"
                 + ("  _(records span multiple dates)_" if len(dates) > 1 else ""))
    for suite, tools in sorted((prov.get("tools") or {}).items()):
        L.append(f"- suite `{suite}`: {'; '.join(tools)}")
    L.append(f"- sources: {', '.join(prov.get('sources', []))}")
    L.append("")
    L.append("> **This file is generated and goes stale.** It reports measurements for the "
             "`vcs_rev` above; if your checkout is at a later commit, re-run "
             "`scripts/bench/run_all.py` before quoting these numbers. "
             "`vcs_dirty: true` means the working tree was modified when measured, so the "
             "numbers do not correspond to any committed state.")
    L.append("")
    L.append("> A BenchmarkDotNet version change invalidates historical .NET "
             "comparisons (AGENTS.md: 8-12% on the headline Ratio, 0.6% noise "
             "floor). Check `tool_version` before comparing two runs.")
    L.append("")

    # ── Per-pair tables ──────────────────────────────────────────────
    for a, b in PAIRS:
        pair_cells = [c for c in size_cells if a in c["impls"] and b in c["impls"]]
        if not pair_cells:
            continue
        # No pair is skipped any more. C and PInvoke used to be aliased to one name,
        # which made a C-vs-PInvoke pair vacuous and this guard correctly dropped it.
        # They are now distinct impls measured in different contexts (direct call vs
        # P/Invoke round-trip), so the pair is the measurement of interop cost itself.
        L.append(f"## {PAIR_TITLES.get((a, b), f'{a} vs {b}')}")
        L.append("")
        L.append(f"Ratio column: time({b}) / time({a}). "
                 f">1 means **{a} is faster**, <1 means **{b} is faster**.")
        L.append("")
        # Name what each side of the pair measures. The .NET suite reaches the C
        # library through P/Invoke; the native suite calls it directly. Their numbers
        # MATCH (XL 4,899,000 vs 4,761,962 us = 2.9%; Medium 7,828 vs 7,600), which is
        # what licenses treating the .NET PInvoke column as a kernel comparison at all.
        # An earlier version of this note blamed P/Invoke marshalling for the Tiny
        # cells; that was wrong, and this cross-suite agreement disproves it - those
        # cells produce ZERO output spikes, so both sides time near-nothing.
        if (a, b) == ("C", "PInvoke"):
            L.append("Both sides run the **same C library**. The left column is the native "
                     "suite calling it directly; the right is the .NET suite reaching it "
                     "through P/Invoke, so P/Invoke marshalling cost is on the right side. "
                     "A ratio near 1.0 means the interop round-trip is not measurable at "
                     "this size; a ratio well above 1 means it is.")
            L.append("")
        if (a, b) == ("PInvoke", "Managed"):
            L.append("Both columns come from the **.NET suite**, so this is a same-process "
                     "comparison: the C library reached through P/Invoke versus the fully "
                     "managed .NET implementation. P/Invoke marshalling cost sits on the "
                     "left side. The Tiny/Small kernel rows are absent from this pair "
                     "because the .NET suite no longer defines them, and sub-10us rows are "
                     "excluded by `below_min_work`. From Medium up, C wins every valid cell.")
            L.append("")
        L.append("| benchmark | size | pattern | " + a + " (us) | " + b + " (us) | ratio | valid |")
        L.append("|---|---|---|---:|---:|---:|:--|")

        def sort_key(c):
            return (c["benchmark"],
                    SIZE_ORDER.index(c["size"]) if c["size"] in SIZE_ORDER else 99,
                    PATTERN_ORDER.index(c["pattern"]) if c["pattern"] in PATTERN_ORDER else 99)

        ratios_valid = []
        ratios_by_size = {}
        for c in sorted(pair_cells, key=sort_key):
            r = ratio(c, a, b)
            ta = fmt_us(c["impls"][a]["mean_ns"])
            tb = fmt_us(c["impls"][b]["mean_ns"])
            flag = "yes" if c["valid"] else "—"
            rs = f"{r:.2f}x" if r else ""
            L.append(f"| {c['benchmark']} | {c['size']} | {c['pattern']} | {ta} | {tb} | {rs} | {flag} |")
            if c["valid"] and r:
                ratios_valid.append(r)
                ratios_by_size.setdefault(c["size"], []).append(r)

        g = geomean(ratios_valid)
        L.append("")
        if g:
            L.append(f"**Geomean over {len(ratios_valid)} valid cells: "
                     f"{winner_phrase(a, b, g)}**")
        else:
            L.append("**Geomean: no valid cells for this pair**")
        L.append("")

        # Per-size geomeans. A single geomean across sizes is misleading when one
        # side has a fixed per-call cost: measured here, C-vs-Managed is 0.20x at
        # Tiny and 0.62x at Small, so the pooled number (0.35x) describes neither
        # size. P/Invoke marshalling is a fixed cost, so it dominates the small
        # cells and amortizes away at the large ones — the same shape the Python
        # kernel benchmarks show (Cython loses at Tiny, wins 4-6x at Medium/Large).
        if len(ratios_by_size) > 1:
            parts = []
            for s in sorted(ratios_by_size, key=lambda s: SIZE_ORDER.index(s)
                            if s in SIZE_ORDER else 99):
                gs = geomean(ratios_by_size[s])
                if gs:
                    parts.append(f"{s} {gs:.2f}x ({len(ratios_by_size[s])})")
            if parts:
                L.append("Per-size geomean (ratio " + f"{b}/{a}"
                         + ", pooled across families): " + ", ".join(parts))
                L.append("")
                L.append("> A fixed per-call cost (P/Invoke marshalling, binding overhead) "
                         "dominates small cells and\n> amortizes at large ones, so the "
                         "pooled geomean describes neither. Read the per-size row.")
                L.append("")

    # ── Excluded rows ────────────────────────────────────────────────
    excluded = [c for c in size_cells if not c["valid"]]
    if excluded:
        L.append("## Excluded from geomeans")
        L.append("")
        L.append("Validity is computed by `merge.py` from `output_spikes`, "
                 "`error_code`, iteration count, and the declared exclusion policy. "
                 "It is not hand-authored.")
        L.append("")
        L.append("| benchmark | size | pattern | reason |")
        L.append("|---|---|---|---|")
        for c in sorted(excluded, key=lambda c: (c["benchmark"], str(c["size"]))):
            L.append(f"| {c['benchmark']} | {c['size']} | {c['pattern']} | "
                     f"{', '.join(c['invalid_reasons'])} |")
        L.append("")

    # ── Sweeps ───────────────────────────────────────────────────────
    if sweeps:
        L.append("## Parameter sweeps")
        L.append("")
        L.append("Kept out of the size table; these vary a parameter, not a size cell.")
        L.append("")
        L.append("| benchmark | size | axis | impl | time (us) |")
        L.append("|---|---|---|---|---:|")
        # `size` must be a column: TrainingLoopSweep registers Tiny AND Small at
        # each batch_size, so without it the table shows two rows per batch_size
        # that look like duplicates of one another.
        for c in sorted(sweeps, key=lambda c: (c["benchmark"], str(c["size"]),
                                               str(c["axis"]))):
            for impl, row in sorted(c["impls"].items()):
                L.append(f"| {c['benchmark']} | {c['size']} | {json.dumps(c['axis'])} | "
                         f"{impl} | {fmt_us(row['mean_ns'])} |")
        L.append("")

    with open(args.out, "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"{args.out}: {len(size_cells)} size cells, "
          f"{len(excluded)} excluded, {len(sweeps)} sweep cells")
    return 0


if __name__ == "__main__":
    sys.exit(main())
