#!/usr/bin/env bash
# build.sh — Build all EventProp projects (C, C++, .NET, Python) on macOS and Linux.
#
# Usage:
#   ./build.sh                      # release
#   ./build.sh debug
#   ./build.sh --skip-python        # skip the two Python layers (reference + Cython)
#   ./build.sh --skip-submodule     # skip scripts/submodule-state.sh apply
#   ./build.sh --clean              # delete each build dir first (flag changes, cache leaks)
#   ./build.sh --python python3.11  # which interpreter gets the Python layers
#
# This is the same contract as build.ps1 on Windows: presets, the same dependency
# order, per-step exit codes, the same nine steps, and a summary that ends in a real
# exit code. Keeping the two scripts the same shape is the point — a fix that lands in
# one and not the other is how the two platforms end up measuring different things.
#
# Why presets, not `mkdir build && cmake ..`
#   The five CMake projects ship CMakePresets.json and AGENTS.md names presets as the
#   supported path. The hand-typed form skips them, which loses:
#     - ENABLE_ASAN=OFF stated explicitly. It is a cache variable, so a previous
#       `--preset asan` leaks and the release build silently produces an
#       ASan-instrumented STATIC library, which breaks the parity tests (they import a
#       SHARED library) and poisons benchmark timings.
#     - the per-project settings the presets own (warning flags, the atomics probe,
#       the SIMD level decided by cmake/EventPropSimd.cmake).
#   Every preset writes to ${sourceDir}/build, which is what the cross-project imports
#   hardcode: EventProp.C.Tests, EventProp.Native.ParityTests and
#   EventProp.Native.Benchmarks each consume a PRE-BUILT library out of
#   EventProp.C/build and EventProp.Cpp.Wrapper/build. The order below is load-bearing,
#   not cosmetic — and it is also why the ABI symbols in eventprop.h are present before
#   the .NET and Cython layers that require them are built.
#
# Why every step's exit code is checked
#   The previous version discarded the Python steps' output and appended `|| true`, so
#   a failed build printed nothing and the script ended with "Build complete". It also
#   installed the Cython bindings ONLY if a project .venv existed, while printing
#   "→ eventprop_c (editable install)" unconditionally — so on a machine with no venv
#   nothing was installed and the log said it was. A build script whose final line is a
#   claim rather than a measurement is how a compile failure reaches a benchmark number.
#
# What it builds that the previous version did not
#   - EventProp.C.Tests (the 220-test Google Test suite)
#   - EventProp.Benchmarks (the .NET benchmark dll) — a prerequisite run_all.py and
#     run_benchmarks.ps1 check for, so a build script that omits it can never satisfy
#     its own check.
#   - _native.c, regenerated by Cython when _native.pyx is newer. The extension
#     compiles _native.c, Cython generates it from _native.pyx, and _native.c is NOT
#     tracked: a fresh clone has none, and an edited .pyx silently does not rebuild.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

BUILD_TYPE="release"
PYTHON="python3"
SKIP_SUBMODULE=0
SKIP_PYTHON=0
CLEAN=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    debug|release) BUILD_TYPE="$1" ;;
    --python) shift; PYTHON="${1:-}" ;;
    --python=*) PYTHON="${1#--python=}" ;;
    --skip-submodule) SKIP_SUBMODULE=1 ;;
    --skip-python) SKIP_PYTHON=1 ;;
    --clean) CLEAN=1 ;;
    -h|--help) sed -n '2,48p' "$0"; exit 0 ;;
    *) echo "Unknown argument: $1"; echo "Usage: $0 [debug|release] [--python EXE] [--clean] [--skip-python] [--skip-submodule]"; exit 1 ;;
  esac
  shift
done

if [[ "$BUILD_TYPE" == "debug" ]]; then
  PRESET="debug"
  DOTNET_CONFIG="Debug"
elif [[ "$BUILD_TYPE" == "release" ]]; then
  PRESET="release"
  DOTNET_CONFIG="Release"
else
  echo "Usage: $0 [debug|release]"
  exit 1
fi

failures=()
skips=()

step() { printf '\n\033[36m[%s]\033[0m %s\n' "$1" "$2"; }

# Run a command, record its failure, keep going. Returns 0 on success.
# The exit code is captured on its own line: `if ! "$@"; then local code=$?` reads the
# status of the negation (always 0/1), not the command's, which is how a build script
# ends up reporting "exit 1" for every failure and losing the real code.
run() {
  local name="$1"; shift
  "$@"
  local code=$?
  if [[ $code -ne 0 ]]; then
    printf '  \033[31mFAILED (exit %d): %s\033[0m\n' "$code" "$name"
    failures+=("$name (exit $code)")
    return 1
  fi
  return 0
}

ok() { printf '  \033[32m→ %s\033[0m\n' "$1"; }
note() { printf '  \033[33m%s\033[0m\n' "$1"; }

# configure+build a CMake project through its presets, from the project dir
build_cmake() {
  local dir="$1" preset="$2" label="$3"
  local full="$SCRIPT_DIR/src/$dir"
  if [[ ! -f "$full/CMakePresets.json" ]]; then
    note "$dir: no CMakePresets.json — configure by hand (see AGENTS.md)"
    skips+=("$dir (no presets)")
    return 1
  fi
  cd "$full" || return 1
  if [[ $CLEAN -eq 1 && -d build ]]; then
    echo "  --clean: removing build/"
    rm -rf build
  fi
  if run "cmake --preset $preset ($dir)" cmake --preset "$preset"; then
    if run "cmake --build --preset $preset ($dir)" cmake --build --preset "$preset"; then
      ok "$label"
      return 0
    fi
  fi
  return 1
}

build_dotnet() {
  local proj="$1"
  run "dotnet build $proj" dotnet build "$proj" -c "$DOTNET_CONFIG" --nologo
}

# Which interpreter gets the Python layers? The one that will RUN the suite:
# scripts/bench/run_all.py invokes every tool with sys.executable, i.e. the interpreter
# that launched it, and run_benchmarks.ps1 defaults to `python`. Installing into a .venv
# that nobody runs produces a tree where the extension is built, the import works under
# the venv, and the benchmark suite still cannot import it. So the venv is a note, not a
# precondition.
py_note_venv() {
  local dir="$1"
  if [[ -f "$dir/.venv/bin/activate" ]]; then
    note "a .venv exists here ($dir/.venv)"
    note "the benchmark runner uses '$PYTHON', so the install targets that."
    note "to build for the venv: ./build.sh --python \"$dir/.venv/bin/python\""
  fi
}

printf '============================================\n'
printf ' EventProp Build — %s (preset "%s")\n' "$BUILD_TYPE" "$PRESET"
printf '============================================\n'

# ── 1. Submodule state ───────────────────────────────────────────────────────
# The reference submodule is read-only and needs local modifications to build: a
# platform patch plus a pybind11 version bump. scripts/submodule-state.sh owns that
# state, is idempotent, and fails loudly — a half-patched submodule surfaces later as an
# opaque compile error inside pybind11/Eigen, far from the cause.
step "1/9" "submodule state (scripts/submodule-state.sh apply)"
if [[ $SKIP_SUBMODULE -eq 1 ]]; then
  note "--skip-submodule"
  skips+=("submodule state (--skip-submodule)")
else
  run "scripts/submodule-state.sh apply" "$SCRIPT_DIR/scripts/submodule-state.sh" apply
fi

# ── 2. C library ─────────────────────────────────────────────────────────────
step "2/9" "C library (EventProp.C)"
build_cmake EventProp.C "$PRESET" "libeventprop_c_api (build/$PRESET)"

# ── 3. Eigen core ────────────────────────────────────────────────────────────
step "3/9" "Eigen core (EventProp.Cpp.Wrapper)"
build_cmake EventProp.Cpp.Wrapper "$PRESET" "eventprop_eigen_core + eventprop_cpp_wrapper"

# ── 4. C unit tests ──────────────────────────────────────────────────────────
# EventProp.C.Tests ships `release` and `asan` presets only, so there is nothing to do
# in debug. Say so: silently omitting a 220-test suite reads as "tests passed".
step "4/9" "C unit tests (EventProp.C.Tests, 220 tests)"
if [[ "$PRESET" == "release" ]]; then
  build_cmake EventProp.C.Tests "release" "eventprop_tests.exe (ctest --preset release)"
else
  note "no 'debug' preset (presets are release + asan) — skipped"
  skips+=("EventProp.C.Tests (no debug preset)")
fi

# ── 5. Parity tests (C vs Eigen) ─────────────────────────────────────────────
step "5/9" "parity tests (C vs Eigen)"
build_cmake EventProp.Native.ParityTests "$PRESET" "parity_test"

# ── 6. Native benchmarks (C vs C++) ──────────────────────────────────────────
# Always the release preset: a Debug benchmark measures the compiler, not the algorithm.
step "6/9" "native benchmarks (C vs C++)"
build_cmake EventProp.Native.Benchmarks "release" "bench_c + bench_cpp"

# ── 7. Reference Python library (pybind11 submodule) ─────────────────────────
step "7/9" "reference Python library (EventProp.Python)"
if [[ $SKIP_PYTHON -eq 1 ]]; then
  note "--skip-python"
  skips+=("EventProp.Python (--skip-python)")
else
  cd "$SCRIPT_DIR/src/EventProp.Python" || exit 1
  py_note_venv "$PWD"
  echo "  interpreter: $PYTHON  $("$PYTHON" --version 2>&1)"

  # Detect the built extension with a nullglob array, not `ls a*.so b*.dylib c*.pyd`:
  # ls exits non-zero if ANY pattern fails to match, so on a machine where the .pyd
  # exists and the .so/.dylib do not, the multi-pattern test reports "not built" and
  # rebuilds (or fails) every run.
  #
  # "Exists" is NOT the right question — "exists FOR THIS INTERPRETER" is. CPython
  # extension filenames carry the ABI tag (eventprop_cpp.cpython-39-darwin.so), and a
  # 3.9 .so is invisible to python3.14. Measured: with only a 3.9 .so present, this
  # step printed "already built" and skipped, so the 3.14 test run died with
  # ModuleNotFoundError: No module named 'eventprop.eventprop_cpp' — in the test
  # suite, several steps after the build that declined to produce it.
  #
  # The tag is asked of the interpreter itself (sysconfig SOABI), not parsed from the
  # version string, so it matches whatever the platform's naming convention is
  # (cpython-314-darwin.so, .cp314-win_amd64.pyd, ...).
  abi_tag="$("$PYTHON" -c 'import sysconfig;print(sysconfig.get_config_var("SOABI"))' 2>/dev/null)"
  built=()
  shopt -s nullglob
  all_ext=(eventprop/eventprop_cpp*.so eventprop/eventprop_cpp*.dylib eventprop/eventprop_cpp*.pyd)
  shopt -u nullglob
  # "${arr[@]}" on an EMPTY array is an unbound variable under `set -u` on bash 3.2
  # (the macOS default) — it dies with "all_ext[@]: unbound variable" on a fresh
  # clone, which is exactly the case where all_ext is empty. The
  # "${arr[@]+"${arr[@]}"}" form expands to nothing when unset and is safe on every
  # bash that has nullglob.
  for f in ${all_ext[@]+"${all_ext[@]}"}; do
    # Match the interpreter's own ABI tag in the filename; a plain .so (no tag) is
    # accepted, since some builds emit the untagged form.
    base="${f##*/}"
    if [[ -z "$abi_tag" ]]; then
      built+=("$f")
    elif [[ "$base" == *"$abi_tag"* || "$base" == "eventprop_cpp.so" ]]; then
      built+=("$f")
    fi
  done
  if [[ ${#built[@]} -gt 0 ]]; then
    ok "eventprop.eventprop_cpp already built for $abi_tag (${built[0]})"
  else
    if [[ ${#all_ext[@]} -gt 0 ]]; then
      note "existing extension(s) are for a DIFFERENT interpreter (none match $abi_tag) — rebuilding"
    fi
    if run "pip install -e . (EventProp.Python)" \
      "$PYTHON" -m pip install --break-system-packages -e .; then
      ok "eventprop.eventprop_cpp (editable install)"
    fi
  fi

  # The benchmark suite package, installed into the same interpreter: run_all.py runs
  # pytest against it with sys.executable.
  cd "$SCRIPT_DIR/src/EventProp.Python.Benchmarks" || exit 1
  if [[ -f pyproject.toml || -f setup.py ]]; then
    if run "pip install -e . (EventProp.Python.Benchmarks)" \
      "$PYTHON" -m pip install --break-system-packages -e .; then
      ok "eventprop-python-benchmarks"
    fi
  fi
fi

# ── 8. Cython bindings ───────────────────────────────────────────────────────
step "8/9" "Cython bindings (EventProp.Native.Python)"
if [[ $SKIP_PYTHON -eq 1 ]]; then
  note "--skip-python"
  skips+=("EventProp.Native.Python (--skip-python)")
else
  cd "$SCRIPT_DIR/src/EventProp.Native.Python" || exit 1
  py_note_venv "$PWD"
  echo "  interpreter: $PYTHON  $("$PYTHON" --version 2>&1)"

  # The extension compiles _native.c, Cython generates it from _native.pyx, and
  # _native.c is NOT tracked — a fresh clone has none, and an edited .pyx silently does
  # not rebuild. The second is the stale-extension class the ABI check in _native.pyx
  # now refuses to import on (AGENTS.md: "ABI: One Version Stamp, Checked by Every
  # Consumer"), so regenerate when the .pyx is newer than the .c.
  #
  # The check must test CONTENT, not just mtime. A failed build under an unsupported
  # interpreter leaves a ZERO-BYTE _native.c (measured: a 3.9.6 run, which the
  # >=3.10 requirement rejects, truncated it to 0 bytes). An empty file is "newer"
  # than the .pyx, so a pure -nt test skips Cython, and pip then compiles the empty
  # file into a ~16 KB stub .so that imports as `ModuleNotFoundError: dynamic module
  # does not define module export function (PyInit__native)` — a failure far from its
  # cause, in a different step, on the next build. -s is the content test.
  pyx="eventprop_c/_native.pyx"
  cfile="eventprop_c/_native.c"
  need_cython=0
  if [[ ! -s "$cfile" ]]; then
    need_cython=1
  elif [[ -f "$pyx" && "$pyx" -nt "$cfile" ]]; then
    need_cython=1
  fi
  if [[ $need_cython -eq 1 ]]; then
    run "cython _native.pyx" "$PYTHON" -m cython "$pyx"
  else
    echo "  _native.c is newer than _native.pyx — skipping cython"
  fi

  # --no-build-isolation: the build needs the interpreter's numpy (the extension
  # compiles against numpy's C API), and an isolated build env fetches its own.
  # The arrow is gated on the exit code. The version this replaced printed
  # "→ eventprop_c (editable install)" unconditionally, and pip's output went to
  # /dev/null with `|| true` — so a failed extension build was reported as success, and
  # the next thing to touch it was the benchmark suite, 40 minutes later.
  if run "pip install -e . (EventProp.Native.Python)" \
    "$PYTHON" -m pip install --break-system-packages -e . --no-build-isolation; then
    ok "eventprop_c (editable install)"
  fi
fi

# ── 9. .NET ──────────────────────────────────────────────────────────────────
# EventProp.Benchmarks is the artifact run_all.py invokes
# (bin/Release/net10.0/EventProp.Benchmarks.dll), so it is built here, not assumed.
step "9/9" ".NET (libraries, tests, benchmarks)"
cd "$SCRIPT_DIR/src" || exit 1
for proj in EventProp EventProp.Native EventProp.Tests EventProp.Benchmarks; do
  build_dotnet "$proj/$proj.csproj"
done

# EventProp.Native/EventProp.Native.csproj copies
# ../EventProp.C/build/Release/libeventprop_c_api into its output, so a debug build of
# the C library is not the one the .NET native tests load. Not a defect to fix here — it
# is a trap to name, because the failure shows up as a P/Invoke load error in a debug run
# that looks unrelated to the build.
if [[ "$DOTNET_CONFIG" == "Debug" ]]; then
  note "EventProp.Native.csproj hardcodes ../EventProp.C/build/Release/libeventprop_c_api"
  note "a debug run loads the RELEASE C library unless that file is a debug build."
fi

# ── Summary ──────────────────────────────────────────────────────────────────
echo ""
printf '============================================\n'
if [[ ${#failures[@]} -eq 0 ]]; then
  printf ' Build complete — %s mode\n' "$BUILD_TYPE"
  printf '============================================\n'
  echo ""
  echo "Run tests:    cd src/EventProp.Tests && dotnet run -c $DOTNET_CONFIG --"
  echo "Run C tests:  cd src/EventProp.C.Tests && ctest --preset release"
  echo "Run parity:   cd src/EventProp.Native.ParityTests && ./build/parity_test ../../EventProp.C/build/libeventprop_c_api.dylib"
  echo "Run bench C:  cd src/EventProp.Native.Benchmarks/build && ./bench_c --benchmark_min_time=0.1s"
  echo "Run bench C++: cd src/EventProp.Native.Benchmarks/build && ./bench_cpp --benchmark_min_time=0.1s"
  echo "Run report:   python3 scripts/bench/run_all.py --quick"
  echo ""
  exit 0
fi

printf ' Build INCOMPLETE — %d step(s) failed:\n' "${#failures[@]}"
for f in "${failures[@]}"; do printf '   - %s\n' "$f"; done
printf '============================================\n'
if [[ ${#skips[@]} -gt 0 ]]; then
  echo ""
  echo "Skipped: ${skips[*]}"
fi
echo ""
echo "A failed step is not a stale artifact: the consumers import these binaries"
echo "pre-built, so a compile failure here reaches a benchmark number as a measurement."
echo ""
exit 1
