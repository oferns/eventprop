#!/usr/bin/env bash
# clean.sh — Remove build outputs from EventProp projects.
#
# Usage: ./clean.sh [-full] [--dry-run] [--python EXE] [target ...]
#   targets: all | c | cpp | python | dotnet | parity | benchmarks | results
#
#   -full        Also delete the EventProp.Python reference binary (forces a rebuild)
#   --dry-run    Print what would be removed; delete nothing
#   --python EXE Interpreter whose `pip uninstall` runs (default: python3)
#
# Targets compose: `./clean.sh c cpp parity` cleans all three. No target means all.
# An unrecognised argument is an error (exit 2), not a silent no-op — the PowerShell
# counterpart used to accept `-Target bogus`, print "Cleaning… Done." and exit 0 while
# removing nothing, which is how a "clean" tree ends up containing a stale build.
#
# Why --dry-run exists: `results` deletes measurement records (bench-results/,
# baselines/*.json, BenchmarkDotNet.Artifacts/) that a 47-minute run produced. A
# destructive target on a benchmark repo should be inspectable before it fires.
#
# Why the extension patterns list every platform suffix
#   The Cython extension and the reference binary are named _native.<abi>-<plat>.pyd on
#   Windows, .so on Linux, .dylib on macOS. clean.sh used to delete `eventprop_c/*.so`
#   and `eventprop_cpp.*.so/.dylib` only: measured on this machine, that matches ZERO
#   files (2 .pyd present, 0 .so), so `clean.sh python` left the compiled extension in
#   place and `-full` printed "→ Deleted reference binary" having deleted nothing —
#   while AGENTS.md claims -full forces a rebuild. Each script was right on the platform
#   the other one covers; both now list all four suffixes.
#
# Why _native.c is removed
#   It is generated by Cython from _native.pyx and is NOT tracked. build.sh regenerates
#   it when _native.pyx is NEWER than _native.c, so a "clean" that leaves _native.c
#   behind makes the next build skip Cython and compile the stale generated C — the
#   stale-extension class the ABI check in _native.pyx refuses to import on. Cleaning
#   the extension without removing _native.c does not clear the condition.
#
# What is NEVER touched: bench-reports/ and BENCHMARKS.md. They are committed
# artifacts (the report is the thing that survives being read on another machine), and a
# clean script that deletes them turns a cleanup into data loss. The `results` target
# removes regenerable measurements only, and stops at the committed boundary.
#
# A project .venv is NOT a build output and is not removed. The reference pybind11
# build inside one is expensive to recreate, and build.sh/run_benchmarks.sh treat the
# interpreter as the user's choice.

set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

FULL=false
DRY_RUN=false
PYTHON="python3"
TARGETS=()
failures=()
removed=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    -full|--full)   FULL=true ;;
    --dry-run|-n)   DRY_RUN=true ;;
    --python)
      shift
      if [[ $# -eq 0 || "${1:0:1}" == "-" ]]; then
        echo "clean.sh: --python requires a value" >&2
        exit 2
      fi
      PYTHON="$1" ;;
    --python=*)     PYTHON="${1#--python=}" ;;
    all)            TARGETS=(all) ;;
    c|cpp|python|dotnet|parity|benchmarks|results) TARGETS+=("$1") ;;
    -h|--help)      sed -n '2,44p' "$0"; exit 0 ;;
    *)
      echo "clean.sh: unknown target '$1'" >&2
      echo "Usage: ./clean.sh [-full] [--dry-run] [--python EXE] [all|c|cpp|python|dotnet|parity|benchmarks|results ...]" >&2
      exit 2 ;;
  esac
  shift
done

if [[ ${#TARGETS[@]} -eq 0 ]]; then TARGETS=(all); fi

has() {
  local want="$1" t
  for t in "${TARGETS[@]}"; do
    [[ "$t" == "all" ]] && return 0
    [[ "$t" == "$want" ]] && return 0
  done
  return 1
}

# rm_tree <path> — remove a directory (or file), record a failure, keep going.
rm_tree() {
  local p="$1"
  [[ -e "$p" ]] || return 0
  if [[ $DRY_RUN == true ]]; then
    printf '  [dry-run] would remove %s\n' "${p#"$SCRIPT_DIR"/}"
    return 0
  fi
  if rm -rf -- "$p"; then
    removed=$((removed + 1))
  else
    printf '  \033[31mFAILED to remove %s\033[0m\n' "$p" >&2
    failures+=("rm $p")
  fi
}

# rm_find <dir> <find-pattern...> — remove files matching, printing each one.
rm_find() {
  local dir="$1"; shift
  [[ -d "$dir" ]] || return 0
  local matches=()
  while IFS= read -r m; do matches+=("$m"); done < <(find "$dir" -maxdepth 1 -type f "$@" 2>/dev/null)
  if [[ ${#matches[@]} -eq 0 ]]; then return 0; fi
  local m
  for m in "${matches[@]}"; do
    if [[ $DRY_RUN == true ]]; then
      printf '  [dry-run] would remove %s\n' "${m#"$SCRIPT_DIR"/}"
    elif rm -f -- "$m"; then
      removed=$((removed + 1))
    else
      printf '  \033[31mFAILED to remove %s\033[0m\n' "$m" >&2
      failures+=("rm $m")
    fi
  done
  printf '  %d file(s) %s\n' "${#matches[@]}" "$([[ $DRY_RUN == true ]] && echo 'matched' || echo 'removed')"
}

# pip_uninstall <dist> — uninstall from the interpreter that will run the suite.
# build.sh and run_benchmarks.sh take --python for exactly this reason: the ambient
# `pip` on this machine is 3.14 while the suite runs on 3.11, so an uninstall aimed at
# `pip` can report success against an interpreter the suite never uses.
pip_uninstall() {
  local dist="$1"
  if [[ $DRY_RUN == true ]]; then
    printf '  [dry-run] would run: %s -m pip uninstall -y %s\n' "$PYTHON" "$dist"
    return 0
  fi
  "$PYTHON" -m pip uninstall -y --quiet "$dist" 2>/dev/null || true
}

# __pycache__ / .pytest_cache, recursively, under a directory — but NOT inside a
# .venv. __pycache__ in a virtualenv belongs to installed packages (numpy's, pytest's);
# deleting it is a surprise, costs a rebuild, and is not this project's build output.
# The .venv itself is the user's choice and is never removed.
clean_pycache() {
  local dir="$1"
  [[ -d "$dir" ]] || return 0
  local d
  while IFS= read -r d; do rm_tree "$d"; done < <(
    find "$dir" \( -name '.venv' -o -name '.git' -o -name 'build' \) -type d -prune -o \
      \( -name '__pycache__' -o -name '.pytest_cache' \) -type d -print 2>/dev/null)
}

printf 'Cleaning EventProp build outputs (targets: %s, full: %s, dry-run: %s, python: %s)\n' \
  "${TARGETS[*]}" "$FULL" "$DRY_RUN" "$PYTHON"

# ── C Library (EventProp.C) ──────────────────────────────────────────────────
if has c; then
  printf '\n[1/9] EventProp.C\n'
  # build-werror is the werror preset's directory; EventProp.C.Tests/build was never
  # cleaned by any target, including `all` — ~30 MB of GTest + test objects forever.
  rm_tree "$SCRIPT_DIR/src/EventProp.C/build"
  rm_tree "$SCRIPT_DIR/src/EventProp.C/build-werror"
  rm_tree "$SCRIPT_DIR/src/EventProp.C.Tests/build"
  rm_tree "$SCRIPT_DIR/src/EventProp.C.Tests/build-werror"
  rm_tree "$SCRIPT_DIR/src/EventProp.C/.cache"          # clangd cache
  rm_tree "$SCRIPT_DIR/src/EventProp.C/compile_commands.json"
fi

# ── C++ Wrapper (EventProp.Cpp.Wrapper) ──────────────────────────────────────
if has cpp; then
  printf '\n[2/9] EventProp.Cpp.Wrapper\n'
  rm_tree "$SCRIPT_DIR/src/EventProp.Cpp.Wrapper/build"
fi

# ── Reference Python library (EventProp.Python, pybind11 submodule) ──────────
if has python; then
  printf '\n[3/9] EventProp.Python (reference library)\n'
  cd "$SCRIPT_DIR/src/EventProp.Python" || exit 1
  pip_uninstall eventprop
  rm_tree build
  shopt -s nullglob
  for d in *.egg-info; do rm_tree "$d"; done
  shopt -u nullglob
  clean_pycache .
  if [[ "$FULL" == true ]]; then
    printf '  reference binary:\n'
    rm_find eventprop -name 'eventprop_cpp.*' \
      \( -name '*.pyd' -o -name '*.dll' -o -name '*.so' -o -name '*.dylib' \)
  fi
fi

# ── Cython bindings (EventProp.Native.Python) ────────────────────────────────
if has python; then
  printf '\n[4/9] EventProp.Native.Python (Cython bindings)\n'
  cd "$SCRIPT_DIR/src/EventProp.Native.Python" || exit 1
  pip_uninstall eventprop_c
  rm_tree build
  shopt -s nullglob
  for d in *.egg-info; do rm_tree "$d"; done
  shopt -u nullglob
  printf '  compiled extension:\n'
  rm_find eventprop_c -name '_native.*' \
    \( -name '*.pyd' -o -name '*.dll' -o -name '*.so' -o -name '*.dylib' \)
  # The generated C: build.sh regenerates it from _native.pyx, and its "regenerate when
  # the .pyx is newer" rule is only meaningful if a clean removes it.
  rm_find eventprop_c -name '_native.c'
  # MSVC emits these alongside the .pyd when linking in place.
  rm_find eventprop_c -name '*.obj'
  rm_find eventprop_c -name '*.exp'
  rm_find eventprop_c -name '*.lib'
  clean_pycache .
fi

# ── Python benchmarks (EventProp.Python.Benchmarks) ──────────────────────────
if has python; then
  printf '\n[5/9] EventProp.Python.Benchmarks\n'
  cd "$SCRIPT_DIR/src/EventProp.Python.Benchmarks" || exit 1
  # .venv deliberately NOT removed: not a build output, and expensive to recreate.
  rm_tree build
  shopt -s nullglob
  for d in *.egg-info; do rm_tree "$d"; done
  shopt -u nullglob
  clean_pycache .
fi

# ── .NET projects ────────────────────────────────────────────────────────────
if has dotnet; then
  printf '\n[6/9] .NET\n'
  cd "$SCRIPT_DIR/src" || exit 1
  # EventProp.Abstractions is a real project (shared Layer contract) with real bin/obj.
  # EventProp.Cpp.Native is NOT a project and never was — the PowerShell script listed
  # it while omitting Abstractions, so `clean.ps1 dotnet` left Abstractions' output.
  for proj in EventProp EventProp.Abstractions EventProp.Native EventProp.Tests EventProp.Benchmarks; do
    rm_tree "$proj/bin"
    rm_tree "$proj/obj"
  done
  rm_tree "$SCRIPT_DIR/src/EventProp.Tests/TestResults"
  rm_tree "$SCRIPT_DIR/coverage-report"
fi

# ── Parity tests (C vs Eigen) ────────────────────────────────────────────────
if has parity; then
  printf '\n[7/9] EventProp.Native.ParityTests\n'
  rm_tree "$SCRIPT_DIR/src/EventProp.Native.ParityTests/build"
fi

# ── Native benchmarks (C vs C++) ─────────────────────────────────────────────
if has benchmarks; then
  printf '\n[8/9] EventProp.Native.Benchmarks\n'
  rm_tree "$SCRIPT_DIR/src/EventProp.Native.Benchmarks/build"
fi

# ── Benchmark pipeline outputs ───────────────────────────────────────────────
# Regenerable measurements only. bench-reports/ and BENCHMARKS.md are COMMITTED and are
# never removed by any target, including this one.
if has results; then
  printf '\n[9/9] benchmark pipeline outputs\n'
  rm_tree "$SCRIPT_DIR/bench-results"
  rm_tree "$SCRIPT_DIR/src/EventProp.Benchmarks/BenchmarkDotNet.Artifacts"
  rm_tree "$SCRIPT_DIR/src/EventProp.Benchmarks/bin/Release/net10.0/BenchmarkDotNet.Artifacts"
  # The native suite's raw JSON; run_benchmarks.sh keeps its scripts tracked.
  rm_find "$SCRIPT_DIR/src/EventProp.Native.Benchmarks/baselines" -name '*.json'
  rm_tree "$SCRIPT_DIR/scripts/bench/__pycache__"
  rm_tree "$SCRIPT_DIR/src/EventProp.Python.Benchmarks/.benchmarks"
fi

printf '\n============================================\n'
if [[ ${#failures[@]} -gt 0 ]]; then
  printf ' Clean INCOMPLETE — %d removal(s) failed:\n' "${#failures[@]}"
  for f in "${failures[@]}"; do printf '   - %s\n' "$f"; done
  printf '============================================\n'
  exit 1
fi
if [[ $DRY_RUN == true ]]; then
  printf ' Dry run — nothing removed. Re-run without --dry-run to apply.\n'
else
  printf ' Clean complete (%d path(s) removed)\n' "$removed"
fi
printf '============================================\n'
printf ' bench-reports/ and BENCHMARKS.md are committed and were not touched.\n'
exit 0
